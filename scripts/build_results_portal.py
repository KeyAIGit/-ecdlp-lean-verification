def build_expected() -> tuple[str, str, str, str, dict]:
    stats = load_json(STATS_PATH)
    researchos = load_json(RESEARCHOS_REGISTRY_PATH)
    product = load_json(PRODUCT_PATH)
    origin = site_origin()
    return (
        normalized(render_markdown(stats, researchos)),
        normalized(render_results_html(stats, researchos, product, origin)),
        normalized(render_sitemap(origin)),
        normalized(render_robots(origin)),
        product,
    )


def check_file(path: Path, expected: str) -> list[str]:
    if not path.exists():
        return [f"missing generated artifact: {path.relative_to(ROOT)}"]
    actual = path.read_text(encoding="utf-8")
    if actual != expected:
        return [f"stale generated artifact: {path.relative_to(ROOT)}"]
    return []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    markdown, results_html, sitemap, robots, _product = build_expected()
    if args.check:
        errors = (
            check_file(MARKDOWN_PATH, markdown)
            + check_file(RESULTS_PATH, results_html)
            + check_file(SITEMAP_PATH, sitemap)
            + check_file(ROBOTS_PATH, robots)
        )
        if not SITE_JS_PATH.exists():
            errors.append("missing public-site enhancement: assets/site.js")
        else:
            site_js = SITE_JS_PATH.read_text(encoding="utf-8")
            for marker in (
                "setupResultsPortal",
                "setupWorkspaceGuide",
                "site-refresh.css",
                'data-nav-page", "results"',
            ):
                if marker not in site_js:
                    errors.append(f"assets/site.js missing results-portal marker: {marker}")
        if not REFRESH_CSS_PATH.exists():
            errors.append("missing public-site clarity layer: assets/site-refresh.css")
        if errors:
            print("results portal check FAILED:", file=sys.stderr)
            for error in errors:
                print(f"- {error}", file=sys.stderr)
            return 1
        print(
            "results portal check OK: index, page, crawl map, navigation hook, "
            "and clarity layer are fresh"
        )
        return 0

    write_text(MARKDOWN_PATH, markdown)
    write_text(RESULTS_PATH, results_html)
    write_text(SITEMAP_PATH, sitemap)
    write_text(ROBOTS_PATH, robots)
    print(
        "wrote verified-results portal: "
        f"{load_json(STATS_PATH)['ledger_rows']} ECDLP rows + "
        f"{load_json(RESEARCHOS_REGISTRY_PATH)['ledger_rows']} ResearchOS rows"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
